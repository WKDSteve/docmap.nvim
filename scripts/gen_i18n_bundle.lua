-- scripts/gen_i18n_bundle.lua — write lua/docmap/core/i18n/bundled.lua from the catalog files beside it.
--
--   nvim -n -i NONE --headless -u NONE -l scripts/gen_i18n_bundle.lua [--check]
--
-- Run it after every change to a `<locale>.json`. `--check` writes nothing and exits 1 when the copy is stale.
--
-- Why the copy exists: the catalogs are JSON files, and not every host of the engine carries files. The
-- packaged binary and the engine docmap-desktop runs in a browser bundle Lua modules and nothing else; a module
-- they can bundle like any other is the one form of the catalogs that reaches them without either being told
-- (docs/i18n.md, "Hosts without the files"). The first release of the catalog had no such module in the tree,
-- and the browser engine printed `<missing-readme> path=...` for every finding.
--
-- Runs under Neovim's Lua and under PUC Lua alike: it reads and writes bytes and needs no `vim`.

local self_dir = (debug.getinfo(1, "S").source:sub(2):gsub("\\", "/"):match("^(.*)/")) or "."
local repo = self_dir .. "/.."
local dir = repo .. "/lua/docmap/core/i18n"

package.path = repo .. "/lua/?.lua;" .. repo .. "/lua/?/init.lua;" .. package.path

local M = {}

---The text of `bundled.lua` for the catalogs on disk.
---
---The locales come from `core/i18n` (`LOCALES`), the one place a locale is named, in that order.
---@param locales string[]
---@param read fun(code: string): string The JSON text of one catalog.
---@return string
function M.render(locales, read)
  local out = {
    "---@module 'docmap.core.i18n.bundled'",
    "--- The interface catalogs as Lua: the JSON text of every `<locale>.json` beside this file, byte for byte.",
    "---",
    "--- GENERATED by `scripts/gen_i18n_bundle.lua`. Do not edit: change the `.json` and run the script.",
    "--- `TESTS/i18n_catalog_spec.lua` fails when the two differ.",
    "---",
    "--- For the hosts that carry Lua modules and no files (the packaged binary, the engine in a browser):",
    "--- `core/i18n` reads this when it cannot read the files.",
    "",
    "-- stylua: ignore",
    "return {",
  }
  for _, code in ipairs(locales) do
    local text = read(code)
    -- The shortest long bracket the text cannot close. A line break opens the string because Lua drops the
    -- first one, and a carriage return would not survive a long string: the files are LF.
    assert(not text:find("\r", 1, true), code .. ".json holds a carriage return")
    local level = 1
    while text:find("]" .. ("="):rep(level) .. "]", 1, true) do
      level = level + 1
    end
    local eq = ("="):rep(level)
    out[#out + 1] = ("  [%q] = [%s[\n%s]%s],"):format(code, eq, text, eq)
  end
  out[#out + 1] = "}"
  out[#out + 1] = ""
  return table.concat(out, "\n")
end

---@param path string
---@return string?
local function slurp(path)
  local fd = io.open(path, "rb")
  if not fd then
    return nil
  end
  local text = fd:read("*a")
  fd:close()
  return text
end

---The text the copy should have right now.
---@return string
function M.current()
  -- `LOCALES` is a plain list; loading the module reads no catalog.
  local locales = require("docmap.core.i18n").LOCALES
  return M.render(locales, function(code)
    return assert(slurp(dir .. "/" .. code .. ".json"), "cannot read " .. code .. ".json")
  end)
end

M.path = dir .. "/bundled.lua"

-- Required by the spec for `render` and `current`; run as a script it writes or checks.
if arg and arg[0] and arg[0]:gsub("\\", "/"):match("gen_i18n_bundle%.lua$") then
  local want = M.current()
  if arg[1] == "--check" then
    if slurp(M.path) ~= want then
      io.stderr:write(
        "lua/docmap/core/i18n/bundled.lua is stale: run scripts/gen_i18n_bundle.lua\n"
      )
      os.exit(1)
    end
    print("bundled.lua is current")
  else
    local fd = assert(io.open(M.path, "wb"))
    fd:write(want)
    fd:close()
    print("wrote lua/docmap/core/i18n/bundled.lua")
  end
end

return M
